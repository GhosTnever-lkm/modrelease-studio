"""Report serialization and human-readable output."""
from __future__ import annotations

import html
import json
import os
import re
import unicodedata
from pathlib import Path
from urllib.parse import quote_from_bytes

from .models import ScanReport


def to_dict(report: ScanReport) -> dict:
    return report.to_dict(include_files=True)


def _is_invisible_or_control(char: str) -> bool:
    category = unicodedata.category(char)
    return category.startswith("C") or category in {"Zl", "Zp"}


def _escape_json_string_controls(document: str) -> str:
    """Escape invisible code points inside JSON strings without changing values."""
    output: list[str] = []
    in_string = False
    escaped = False
    for char in document:
        if in_string:
            if escaped:
                output.append(char)
                escaped = False
            elif char == "\\":
                output.append(char)
                escaped = True
            elif char == '"':
                output.append(char)
                in_string = False
            elif _is_invisible_or_control(char):
                output.append(json.dumps(char, ensure_ascii=True)[1:-1])
            else:
                output.append(char)
        else:
            output.append(char)
            if char == '"':
                in_string = True
    return "".join(output)


def json_report(report: ScanReport) -> str:
    """Serialize a shareable JSON report while escaping invisible string controls."""
    document = json.dumps(to_dict(report), ensure_ascii=False, indent=2)
    return _escape_json_string_controls(document)


def write_json(report: ScanReport, path: str | Path) -> None:
    Path(path).write_text(json_report(report) + "\n", encoding="utf-8")


def _safe_markdown_cell(value: str) -> str:
    value = value.replace("\r\n", " ").replace("\r", " ").replace("\n", " ").replace("\t", " ")
    value = "".join(f"\\u{{{ord(char):04x}}}" if _is_invisible_or_control(char) else char for char in value)
    escaped = html.escape(value, quote=False)
    entities = {ord(char): f"&#{ord(char)};" for char in "\\|`*_{}[]!#>~:@"}
    return escaped.translate(entities)


def markdown(report: ScanReport) -> str:
    lines = ["# ModRelease Studio report", "", f"- Source: {_safe_markdown_cell(report.target)}", f"- Profile: `{report.profile}`",
             f"- SHA-256: `{report.sha256}`", f"- Files scanned: **{report.file_count}** ({report.total_bytes:,} bytes)",
             f"- Status: **{report.status}**", f"- Findings: **{report.errors} errors, {report.warnings} warnings**", ""]
    if not report.findings:
        lines += ["## Result", "", "No configured release checks reported a problem.", ""]
    else:
        lines += ["## Findings", "", "| Severity | Check | File | Details |", "|---|---|---|---|"]
        for item in report.findings:
            detail = _safe_markdown_cell(item.message)
            path = _safe_markdown_cell(item.path or "—")
            lines.append(f"| {item.severity} | `{item.code}` | {path} | {detail} |")
        lines.append("")
    lines += ["---", "Generated by [ModRelease Studio](https://github.com/GhosTnever-lkm/modrelease-studio).", ""]
    return "\n".join(lines)


def write_markdown(report: ScanReport, path: str | Path) -> None:
    Path(path).write_text(markdown(report), encoding="utf-8")


_NO_FILE_LOCATION = {
    "MISSING_RELEASE_FILE", "REQUIRED_PATH_MISSING", "SCAN_DIRECTORY",
    "ENTRY_LIMIT", "ARCHIVE_SIZE_LIMIT", "INVALID_ZIP",
}


def _artifact_uri(path: str | None) -> str | None:
    if not path:
        return None
    normalized = path.replace("\\", "/")
    parts = normalized.split("/")
    if normalized.startswith("/") or any(part in {"", ".", ".."} for part in parts) or (parts and ":" in parts[0]) or normalized == "—":
        return None
    return quote_from_bytes(os.fsencode(normalized), safe="/-._~!$&'()*+,;=:@")


def _normalize_sarif_prefix(path_prefix: str) -> str:
    """Normalize harmless relative dot segments and reject unsafe prefixes."""
    normalized = path_prefix.replace("\\", "/")
    if normalized.startswith("/"):
        raise ValueError("SARIF path prefix must be repository-relative and cannot contain '..' or drive syntax")

    parts = normalized.split("/")
    if any(part == ".." for part in parts):
        raise ValueError("SARIF path prefix must be repository-relative and cannot contain '..' or drive syntax")
    parts = [part for part in parts if part not in {"", "."}]
    if parts and ":" in parts[0]:
        raise ValueError("SARIF path prefix must be repository-relative and cannot contain '..' or drive syntax")
    return "/".join(parts)


def sarif(report: ScanReport, *, version: str, path_prefix: str = "") -> dict:
    """Build a SARIF 2.1.0 report using only repository-relative file paths."""
    normalized_prefix = _normalize_sarif_prefix(path_prefix)
    prefix = _artifact_uri(normalized_prefix) if normalized_prefix else ""
    if prefix is None:
        raise ValueError("SARIF path prefix must be repository-relative and cannot contain '..' or drive syntax")
    prefix = prefix.rstrip("/")
    rule_ids = sorted({item.code for item in report.findings})
    results = []
    for item in report.findings:
        result = {
            "ruleId": item.code,
            "level": {"ERROR": "error", "WARNING": "warning", "INFO": "note"}.get(item.severity, "warning"),
            "message": {"text": "".join(f"\\u{ord(char):04x}" if _is_invisible_or_control(char) else char for char in item.message)},
        }
        finding_path = item.path or ""
        line = None
        if item.code not in _NO_FILE_LOCATION:
            match = re.fullmatch(r"(.+):(\d+)", finding_path)
            if match:
                finding_path, line = match.group(1), int(match.group(2))
        artifact_uri = _artifact_uri(finding_path) if item.code not in _NO_FILE_LOCATION else None
        if artifact_uri:
            physical_location = {"artifactLocation": {"uri": f"{prefix}/{artifact_uri}" if prefix else artifact_uri}}
            if line is not None:
                physical_location["region"] = {"startLine": line}
            result["locations"] = [{"physicalLocation": physical_location}]
        results.append(result)

    return {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {
                "name": "ModRelease Studio",
                "semanticVersion": version,
                "informationUri": "https://github.com/GhosTnever-lkm/modrelease-studio",
                "rules": [{"id": code, "shortDescription": {"text": code}} for code in rule_ids],
            }},
            "results": results,
            "columnKind": "utf16CodeUnits",
        }],
    }


def write_sarif(report: ScanReport, path: str | Path, *, version: str, path_prefix: str = "") -> None:
    document = sarif(report, version=version, path_prefix=path_prefix)
    Path(path).write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
